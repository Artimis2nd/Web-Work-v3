-- 1. ตารางรายชื่อคนงาน (Workers)
CREATE TABLE IF NOT EXISTS public.workers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    daily_wage NUMERIC(10, 2) NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'Inactive')),
    role TEXT NOT NULL DEFAULT 'Worker' CHECK (role IN ('Supervisor', 'Worker')),
    gender TEXT NOT NULL DEFAULT 'M' CHECK (gender IN ('M', 'F')),
    base_age INTEGER NOT NULL DEFAULT 30,
    registered_date DATE NOT NULL DEFAULT CURRENT_DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. ตารางใบสั่งงาน / งานโครงการ (Tasks / Job Orders)
CREATE TABLE IF NOT EXISTS public.tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_code TEXT NOT NULL UNIQUE,
    title TEXT NOT NULL,
    site TEXT NOT NULL DEFAULT '',
    location_detail TEXT DEFAULT '',
    assigned_to TEXT DEFAULT '',
    ordered_by TEXT DEFAULT '',
    order_date DATE NOT NULL DEFAULT CURRENT_DATE,
    due_date DATE,
    status TEXT NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending', 'In Progress', 'Blocked', 'Completed')),
    progress_percent INT NOT NULL DEFAULT 0 CHECK (progress_percent BETWEEN 0 AND 100),
    description TEXT DEFAULT '',
    issues TEXT DEFAULT '',
    resolution TEXT DEFAULT '',
    completion_summary TEXT DEFAULT '',
    progress_history JSONB NOT NULL DEFAULT '[]'::jsonb,
    accumulated_cost NUMERIC(12, 2) NOT NULL DEFAULT 0,
    accumulated_markup_cost NUMERIC(12, 2) NOT NULL DEFAULT 0,
    accumulated_hours NUMERIC(8, 2) NOT NULL DEFAULT 0,
    accumulated_man_days NUMERIC(8, 2) NOT NULL DEFAULT 0,
    accumulated_days INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- สร้าง Index สำหรับ tasks เพื่อให้ค้นหาตามสถานะ ไซต์งาน และรหัสใบสั่งงานได้รวดเร็ว
CREATE INDEX IF NOT EXISTS idx_tasks_status ON public.tasks (status);
CREATE INDEX IF NOT EXISTS idx_tasks_site ON public.tasks (site);
CREATE INDEX IF NOT EXISTS idx_tasks_task_code ON public.tasks (task_code);

-- 3. ตารางบันทึกใบงานประจำวัน (Daily Logs)
CREATE TABLE IF NOT EXISTS public.daily_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id TEXT NOT NULL,
    work_date DATE NOT NULL,
    site TEXT NOT NULL DEFAULT '',
    job_detail TEXT DEFAULT '',
    requested_by TEXT DEFAULT '',
    worker_name TEXT NOT NULL,
    daily_wage NUMERIC(10, 2) NOT NULL DEFAULT 0,
    wage_type TEXT NOT NULL DEFAULT 'hourly' CHECK (wage_type IN ('hourly', 'fixed')),
    hours NUMERIC(5, 2) NOT NULL DEFAULT 0,
    ot_hours NUMERIC(5, 2) NOT NULL DEFAULT 0,
    fixed_amount NUMERIC(10, 2) NOT NULL DEFAULT 0,
    raw_wage NUMERIC(10, 2) NOT NULL DEFAULT 0,
    total_with_markup NUMERIC(10, 2) NOT NULL DEFAULT 0,
    task_id BIGINT REFERENCES public.tasks(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- อัปเดตโครงสร้าง daily_logs เพิ่มคอลัมน์ task_id สำหรับฐานข้อมูลเดิม
ALTER TABLE public.daily_logs ADD COLUMN IF NOT EXISTS task_id BIGINT REFERENCES public.tasks(id) ON DELETE SET NULL;

-- สร้าง Index เพื่อให้ค้นหาตามใบงาน วันที่ ชื่อคนงาน ไซต์งาน และใบสั่งงาน (task_id) ได้รวดเร็วทันที
CREATE INDEX IF NOT EXISTS idx_daily_logs_group_id ON public.daily_logs (group_id);
CREATE INDEX IF NOT EXISTS idx_daily_logs_work_date ON public.daily_logs (work_date DESC);
CREATE INDEX IF NOT EXISTS idx_daily_logs_worker_name ON public.daily_logs (worker_name);
CREATE INDEX IF NOT EXISTS idx_daily_logs_site ON public.daily_logs (site);
CREATE INDEX IF NOT EXISTS idx_daily_logs_task_id ON public.daily_logs (task_id);

-- 4. ตารางเก็บรูปภาพประจำใบงาน (Log Images)
CREATE TABLE IF NOT EXISTS public.log_images (
    group_id TEXT PRIMARY KEY,
    image_urls JSONB NOT NULL DEFAULT '[]'::jsonb,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 5. ตารางเก็บสำรองข้อมูลเบิกงวด (Backups)
CREATE TABLE IF NOT EXISTS public.log_backups (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    name TEXT NOT NULL,
    logs_data JSONB NOT NULL DEFAULT '[]'::jsonb,
    images_data JSONB NOT NULL DEFAULT '[]'::jsonb,
    tasks_data JSONB DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ============================================================================
-- ตั้งค่าสิทธิ์การเข้าถึงข้อมูล (Row Level Security - RLS)
-- เปิดให้เว็บแอปสามารถอ่าน-เขียนข้อมูลผ่าน Anon Key ได้เหมือนระบบเดิม
-- ============================================================================

ALTER TABLE public.workers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tasks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.daily_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.log_images ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.log_backups ENABLE ROW LEVEL SECURITY;

-- ลบ Policy เดิมถ้ามี (เผื่อรันซ้ำ)
DROP POLICY IF EXISTS "Allow public access on workers" ON public.workers;
DROP POLICY IF EXISTS "Allow public access on tasks" ON public.tasks;
DROP POLICY IF EXISTS "Allow public access on daily_logs" ON public.daily_logs;
DROP POLICY IF EXISTS "Allow public access on log_images" ON public.log_images;
DROP POLICY IF EXISTS "Allow public access on log_backups" ON public.log_backups;

CREATE POLICY "Allow public access on workers"
    ON public.workers FOR ALL
    USING (true)
    WITH CHECK (true);

CREATE POLICY "Allow public access on tasks"
    ON public.tasks FOR ALL
    USING (true)
    WITH CHECK (true);

CREATE POLICY "Allow public access on daily_logs"
    ON public.daily_logs FOR ALL
    USING (true)
    WITH CHECK (true);

CREATE POLICY "Allow public access on log_images"
    ON public.log_images FOR ALL
    USING (true)
    WITH CHECK (true);

CREATE POLICY "Allow public access on log_backups"
    ON public.log_backups FOR ALL
    USING (true)
    WITH CHECK (true);

-- ============================================================================
-- 6. สร้างที่เก็บไฟล์รูปภาพ (Storage Bucket: wage-images) อัตโนมัติ
-- ============================================================================

INSERT INTO storage.buckets (id, name, public)
VALUES ('wage-images', 'wage-images', true)
ON CONFLICT (id) DO UPDATE SET public = true;

DROP POLICY IF EXISTS "Public Read Access for wage-images" ON storage.objects;
DROP POLICY IF EXISTS "Public Upload Access for wage-images" ON storage.objects;
DROP POLICY IF EXISTS "Public Delete Access for wage-images" ON storage.objects;

CREATE POLICY "Public Read Access for wage-images"
    ON storage.objects FOR SELECT
    USING (bucket_id = 'wage-images');

CREATE POLICY "Public Upload Access for wage-images"
    ON storage.objects FOR INSERT
    WITH CHECK (bucket_id = 'wage-images');

CREATE POLICY "Public Delete Access for wage-images"
    ON storage.objects FOR DELETE
    USING (bucket_id = 'wage-images');
