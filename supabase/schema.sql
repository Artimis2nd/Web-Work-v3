-- ============================================================================
-- ระบบคิดค่าแรงคนงาน (Wage Management System) — Supabase Database Schema
-- วิธีใช้: คัดลอกโค้ดทั้งหมดนี้ไปวางในเมนู "SQL Editor" บนเว็บ Supabase แล้วกด "Run"
